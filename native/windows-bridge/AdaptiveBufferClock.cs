namespace LouderMeAudioBridge;

/// <summary>
/// A bounded, slowly-varying, proportional buffer-occupancy controller.
/// Positive ppm means fewer rendered output frames per input frame and
/// therefore slows buffer growth. Negative ppm does the opposite.
/// It does not change the Windows system clock or device sample rates.
/// </summary>
internal sealed class AdaptiveBufferClock
{
    internal const double MaximumCorrectionPpm = 250.0;
    internal const double TargetBufferedMs = 50.0;
    private double _ppm;

    public double CurrentPpm => _ppm;

    public double Update(double bufferedMilliseconds)
    {
        if (!double.IsFinite(bufferedMilliseconds) || bufferedMilliseconds < 0)
            throw new ArgumentOutOfRangeException(nameof(bufferedMilliseconds));

        // Small occupancy excursions are normal with WASAPI timer jitter.
        // Allow a steady-state offset of a few milliseconds in return for
        // avoiding fast pitch modulation or a hunt around the target.
        double error = bufferedMilliseconds - TargetBufferedMs;
        double desiredPpm = Math.Clamp(error * 30.0,
            -MaximumCorrectionPpm, MaximumCorrectionPpm);
        _ppm += 0.15 * (desiredPpm - _ppm);
        _ppm = Math.Clamp(_ppm, -MaximumCorrectionPpm, MaximumCorrectionPpm);
        return _ppm;
    }

    public void Reset() => _ppm = 0;

    public static void RunSelfTests()
    {
        var c = new AdaptiveBufferClock();
        if (Math.Abs(c.Update(TargetBufferedMs)) > 0.001)
            throw new InvalidOperationException("Clock controller changed a balanced queue.");
        for (int n = 0; n < 120; n++) c.Update(250);
        if (c.CurrentPpm is < 249.9 or > MaximumCorrectionPpm)
            throw new InvalidOperationException("Positive drift limit failed.");
        c.Reset();
        for (int n = 0; n < 120; n++) c.Update(0);
        if (c.CurrentPpm is > -249.9 or < -MaximumCorrectionPpm)
            throw new InvalidOperationException("Negative drift limit failed.");

        // Synthetic independent endpoint clocks, with each observation
        // separated by 250 ms. The input stream is generated at 48 kHz
        // nominal; the sink consumes at a different *real* rate.
        foreach (double sinkDriftPpm in new[] { -160.0, 160.0 })
        {
            c.Reset();
            double occupancy = TargetBufferedMs;
            for (int step = 0; step < 4000; step++)
            {
                double correction = c.Update(occupancy);
                // Approximate output generated by the adapter as a function
                // of its ppm-controlled frame step; compare sink consumption.
                occupancy += 250 * (1 / (1 + correction * 0.000001) -
                                     (1 + sinkDriftPpm * 0.000001));
                if (!double.IsFinite(occupancy) ||
                    occupancy < 12 || occupancy > 90)
                    throw new InvalidOperationException(
                        "Simulated buffer underrun/overflow under bounded clock drift.");
            }
            if (Math.Abs(c.CurrentPpm + sinkDriftPpm) > 12)
                throw new InvalidOperationException(
                    "Clock controller did not compensate synthetic source/sink drift.");
        }

        try
        {
            c.Update(double.NaN);
            throw new InvalidOperationException("NaN queue fill was accepted.");
        }
        catch (ArgumentOutOfRangeException) { }
        Console.WriteLine("PASS: bounded ±250 ppm drift controller; " +
            "synthetic independent sink clocks ±160 ppm stay stable.");
    }
}
